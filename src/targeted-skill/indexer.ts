import { readdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { parse as parseYaml } from "yaml";

function splitFrontmatter(text: string): { frontmatter: string; body: string } {
  if (!text.startsWith("---")) return { frontmatter: "", body: text };
  const end = text.indexOf("\n---", 3);
  return end < 0
    ? { frontmatter: "", body: text }
    : { frontmatter: text.slice(3, end).trim(), body: text.slice(end + 4) };
}

export function skillDescription(text: string): string {
  const { frontmatter, body } = splitFrontmatter(text);
  try {
    const metadata = parseYaml(frontmatter);
    if (typeof metadata?.description === "string" && metadata.description.trim()) {
      return metadata.description.trim().replace(/\s+/g, " ").slice(0, 400);
    }
  } catch {
    // Fall back to body paragraphs.
  }
  const description = /^##\s+Description\s*$\n([\s\S]*?)(?=^#{1,6}\s|$)/mi.exec(body)?.[1]
    ?? body.split(/\n\s*\n/).find((block) => block.trim() && !block.trim().startsWith("#"))
    ?? "(no description)";
  return description.trim().replace(/^>\s*/gm, "").replace(/^#{1,6}\s*/gm, "").replace(/\s+/g, " ").slice(0, 400);
}

export async function skillFolders(skillsDir: string): Promise<string[]> {
  try {
    const entries = await readdir(skillsDir, { withFileTypes: true });
    const folders: string[] = [];
    for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name))) {
      if (!entry.isDirectory()) continue;
      try {
        await readFile(join(skillsDir, entry.name, "SKILL.md"), "utf8");
        folders.push(entry.name);
      } catch {
        // Not a skill folder.
      }
    }
    return folders;
  } catch {
    return [];
  }
}

export async function regenerateSkillIndex(skillsDir: string): Promise<{ path: string; count: number }> {
  const folders = await skillFolders(skillsDir);
  const lines = ["# Analysis Recipe Index", "> Auto-generated by SeekBrain", `> Total recipes: ${folders.length}`, ""];
  for (const folder of folders) {
    const text = await readFile(join(skillsDir, folder, "SKILL.md"), "utf8");
    lines.push(`## \`${folder}\``, skillDescription(text), "");
  }
  const path = join(skillsDir, "INDEX.md");
  await writeFile(path, `${lines.join("\n").trimEnd()}\n`, "utf8");
  return { path, count: folders.length };
}

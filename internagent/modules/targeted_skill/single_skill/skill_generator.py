def generate_skill(                                                                                                                                     
    question: dict,
    context: dict,                                                                                                                                       
    paper_info: dict,                                                                                            
    repo_info: dict,                   
    output_base: Path = OUTPUT_DIR,
    skill_dir: Path = None,        
) -> Path:
    """
    Generate a complete skill folder for one question.

    Directory structure:
        output_base/<tag>/
            SKILL.md
            metadata.json
            scripts/
                run_analysis.py
                utils.py (optional)
            references/
                question.md
                paper_context.md
                repo_context.md
                connection_analysis.md
                reproduction_plan.md
                paper_structured_summary.md
                paper_figure_methods.md
                repo_overview.md
                repo_file_summaries.md
                matched_files/
                    <relevant repo files>

    Returns:
        Path to the generated skill directory.
    """
    # tag = context["tag"]
    # skill_dir = output_base / safe_filename(tag)
    tag = context["tag"]
    if skill_dir is None:
        skill_dir = output_base / safe_filename(tag) 
    scripts_dir = skill_dir / "scripts"
    references_dir = skill_dir / "references"
    matched_files_dir = references_dir / "matched_files"

    logger.info(f"Generating skill for [{tag}] at: {skill_dir}")

    # =========================================================================
    # 1. Create directory structure
    # =========================================================================
    scripts_dir.mkdir(parents=True, exist_ok=True)
    references_dir.mkdir(parents=True, exist_ok=True)
    matched_files_dir.mkdir(parents=True, exist_ok=True)

    # =========================================================================
    # 2. Write all reference files
    # =========================================================================
    logger.info(f"  [{tag}] Writing reference files...")

    write_text_file(
        references_dir / "question.md",
        f"# Original Question: {tag}\n\n{context['question_text']}"
    )
    write_text_file(
        references_dir / "paper_context.md",
        f"# Paper Context for {tag}\n\n{context['matched_paper_context']}"
    )
    write_text_file(
        references_dir / "repo_context.md",
        f"# Repository Context for {tag}\n\n{context['matched_repo_context']}"
    )
    write_text_file(
        references_dir / "connection_analysis.md",
        f"# Paper-Repo Connection Analysis for {tag}\n\n{context['connection_analysis']}"
    )
    write_text_file(
        references_dir / "reproduction_plan.md",
        f"# Reproduction Plan for {tag}\n\n{context['reproduction_plan']}"
    )
    write_text_file(
        references_dir / "paper_structured_summary.md",
        f"# Full Paper Structured Summary\n\n{paper_info['structured_summary']}"
    )
    write_text_file(
        references_dir / "paper_figure_methods.md",
        f"# Paper Figure-Method Mapping\n\n{paper_info['figure_methods']}"
    )
    write_text_file(
        references_dir / "repo_overview.md",
        f"# Repository Overview\n\n{repo_info['repo_overview']}\n\n{repo_info['directory_tree']}"
    )

    # File summaries index
    summaries_content = "# Repository File Summaries\n\n"
    for rel_path, summary in repo_info["file_summaries"].items():
        summaries_content += f"## {rel_path}\n\n{summary}\n\n---\n\n"
    write_text_file(references_dir / "repo_file_summaries.md", summaries_content)

    # Matched repo files
    for mf in context.get("matched_repo_files", []):
        rel_path = mf["relative_path"]
        safe_name = safe_filename(rel_path)
        header = f"# Source: {rel_path}\n# Summary: See repo_context.md\n\n"
        write_text_file(matched_files_dir / safe_name, header + mf["content"])

    logger.info(f"  [{tag}] Reference files written.")

    # =========================================================================
    # 3. Generate scripts (writes files to scripts_dir)
    # =========================================================================
    llm = _get_llm()
    generated_scripts = _generate_scripts(tag, context, llm, scripts_dir)

    # =========================================================================
    # 4. Generate SKILL.md in three stages
    # =========================================================================

    # Stage A: Generate YAML metadata (programmatic, validated)
    yaml_metadata = _generate_yaml_metadata(tag, context, llm)
    yaml_front_matter = _serialize_yaml_front_matter(yaml_metadata)

    # Stage B: Generate body content (LLM, no YAML, no file structure)
    body = _generate_skill_md_body(tag, context, llm)

    # Stage C: Build file structure from actual disk contents
    file_structure = _build_file_structure_section(skill_dir)

    # Assemble final SKILL.md
    skill_md_content = _assemble_skill_md(yaml_front_matter, body, file_structure)

    # Post-process and validate
    skill_md_content = _validate_skill_md(skill_md_content, tag)

    write_text_file(skill_dir / "SKILL.md", skill_md_content)
    logger.info(f"  [{tag}] SKILL.md written and validated.")

    # =========================================================================
    # 5. Write metadata.json
    # =========================================================================
    ref_files = sorted([
        str(rf.relative_to(skill_dir))
        for rf in references_dir.rglob("*") if rf.is_file()
    ])
    script_file_list = sorted([
        str(sf.relative_to(skill_dir))
        for sf in scripts_dir.rglob("*") if sf.is_file()
    ])

    metadata = {
        "tag": tag,
        "question_path": question.get("question_rel_path", ""),
        "skill_dir": str(skill_dir),
        "yaml_metadata": yaml_metadata,
        "scripts": script_file_list,
        "references": ref_files,
        "matched_repo_files": [mf["relative_path"] for mf in context.get("matched_repo_files", [])],
    }
    write_text_file(
        skill_dir / "metadata.json",
        json.dumps(metadata, indent=2, ensure_ascii=False)
    )

    logger.info(f"  [{tag}] Skill generation complete: {skill_dir}")
    return skill_dir
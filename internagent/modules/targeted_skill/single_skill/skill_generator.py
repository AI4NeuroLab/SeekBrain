"""
Module to generate a complete Skill folder structure from matched context.
Each skill includes SKILL.md, scripts/, and references/.

KEY FIXES:
- YAML front matter is programmatically constructed, NOT left to LLM hallucination.
- File structure block is built from actual disk contents AFTER all files are written.
- SKILL.md body content is generated by LLM, then assembled with validated YAML header.
- Post-processing validates the final SKILL.md.
"""


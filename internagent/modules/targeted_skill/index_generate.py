#!/usr/bin/env python3
"""Regenerate a loader-compatible ``INDEX.md`` for a skills directory.

Usage::

    python index_generate.py --skills-dir library/skills/from_expert
"""

from __future__ import annotations

import argparse
import re
from datetime import datetime, timezone
from pathlib import Path
from typing import Iterator, Optional

try:  # PyYAML is in requirements; degrade gracefully if unavailable.
    import yaml  # type: ignore
except Exception:  # pragma: no cover
    yaml = None


def _read(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8")
    except Exception:
        return ""


def _split_frontmatter(text: str) -> tuple[str, str]:
    """Return (frontmatter, body). Frontmatter is empty when there is none."""
    if text.startswith("---"):
        end = text.find("\n---", 3)
        if end != -1:
            return text[3:end].strip(), text[end + 4:]
    return "", text


def _desc_from_frontmatter(fm: str) -> Optional[str]:
    if not fm:
        return None
    if yaml is not None:
        try:
            data = yaml.safe_load(fm)
            if isinstance(data, dict):
                d = data.get("description")
                if isinstance(d, str) and d.strip():
                    return d.strip()
        except Exception:
            pass
    m = re.search(r"^description:\s*(.*)$", fm, re.MULTILINE)
    if not m:
        return None
    val = m.group(1).strip()
    if val in ("|", ">", "|-", ">-", "|+", ">+"):  # block scalar -> gather indented lines
        collected: list[str] = []
        for line in fm[m.end():].splitlines():
            if not line.strip():
                if collected:
                    break
                continue
            if line.startswith((" ", "\t")):
                collected.append(line.strip())
            else:
                break
        return " ".join(collected).strip() or None
    return val.strip().strip("\"'").strip() or None


def _first_paragraph(text: str, max_chars: int = 400) -> str:
    para = re.split(r"\n\s*\n", text.strip())[0]
    para = " ".join(para.split())
    if len(para) > max_chars:
        para = para[:max_chars].rsplit(" ", 1)[0] + " ..."
    return para


def _desc_from_body(body: str) -> Optional[str]:
    m = re.search(r"^##\s+Description\s*$\n(.*?)(?=^#{1,6}\s|\Z)", body, re.MULTILINE | re.DOTALL)
    if m and m.group(1).strip():
        return _first_paragraph(m.group(1))
    for block in re.split(r"\n\s*\n", body):
        b = block.strip()
        if b and not b.startswith("#") and not b.startswith("```") and not b.startswith(">"):
            return _first_paragraph(b)
    return None


def _sanitize(desc: str) -> str:
    """Collapse to a single line and strip leading markdown hashes/quotes.

    Critical: the description must not contain a line beginning with ``##``/``###``
    or it would be mis-parsed as the next skill heading by the loader regex.
    """
    desc = re.sub(r"(?m)^\s*#{1,6}\s*", "", desc)
    desc = re.sub(r"(?m)^\s*>\s*", "", desc)
    desc = " ".join(desc.split())
    return desc or "(no description)"


def skill_description(skill_dir: Path) -> str:
    fm, body = _split_frontmatter(_read(skill_dir / "SKILL.md"))
    desc = _desc_from_frontmatter(fm) or _desc_from_body(body) or ""
    return _sanitize(desc)


def iter_skill_folders(skills_dir: Path) -> Iterator[Path]:
    for child in sorted(skills_dir.iterdir()):
        if child.is_dir() and (child / "SKILL.md").is_file():
            yield child


def regenerate_index(skills_dir) -> Path:
    """Rebuild ``<skills_dir>/INDEX.md`` from every sub-folder containing SKILL.md."""
    skills_dir = Path(skills_dir)
    folders = list(iter_skill_folders(skills_dir))
    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
    lines = [
        "# Skills Index",
        f"> Auto-generated by index_generate.py at {stamp}",
        f"> Total skills: {len(folders)}",
        "",
    ]
    for folder in folders:
        lines.append(f"## `{folder.name}`")
        lines.append(skill_description(folder))
        lines.append("")
    index_path = skills_dir / "INDEX.md"
    index_path.write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")
    return index_path


def main() -> None:
    ap = argparse.ArgumentParser(description="Regenerate a loader-compatible INDEX.md.")
    ap.add_argument("--skills-dir", required=True, help="Skills directory to (re)index.")
    args = ap.parse_args()
    path = regenerate_index(args.skills_dir)
    total = sum(1 for _ in iter_skill_folders(Path(args.skills_dir)))
    print(f"Wrote {path} ({total} skills)")


if __name__ == "__main__":
    main()

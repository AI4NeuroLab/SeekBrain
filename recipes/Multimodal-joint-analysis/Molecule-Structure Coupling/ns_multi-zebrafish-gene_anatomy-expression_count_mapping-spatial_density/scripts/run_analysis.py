#!/usr/bin/env python3
"""
Spatial Mapping of eomesa/pvalb7 neurons from EASI-FISH data.

Purpose:
    This script processes cell-wise gene expression count matrices to identify
    spatial distributions of eomesa-positive, pvalb7-positive, and co-expressing 
    neurons. It maps these to anatomical regions using atlas annotations and 
    generates 3D visualization data structures for downstream rendering.

Methodology Mapping:
    - Pipeline Ref: Based on 'assign_spots.py' methodology.
    - Post-processing: Implements the >3 spot thresholding rule for cell-type 
      classification as defined in EASI-FISH study protocols.
    - Spatial Context: Integrates cell coordinates with MapZebrain labels.

Inputs:
    - counts.csv: Generated by assign_spots.py containing cell IDs and gene counts.
    - atlas_labels.csv: MapZebrain metadata mapping IDs to anatomical regions 
      (e.g., Dorsal Pallium, Cerebellum).

Outputs:
    - filtered_cells.parquet: Classified cell types (eomesa+, pvalb+, co-expr).
    - 3D_plot_data.csv: Coordinates ready for visualization.
    - visualization_summary.json: Count metrics per region.
"""

import pandas as pd
import numpy as np
import argparse
import logging
import json
import os
from pathlib import Path

# Configure logging
logging.basicConfig(level=logging.INFO, format='%(asctime)s - %(levelname)s - %(message)s')
logger = logging.getLogger(__name__)

def load_data(counts_path, atlas_path):
    """Loads and validates input datasets."""
    if not os.path.exists(counts_path) or not os.path.exists(atlas_path):
        raise FileNotFoundError("Input count or atlas files missing.")
    
    counts = pd.read_csv(counts_path, index_col=0)
    atlas = pd.read_csv(atlas_path)
    return counts, atlas

def classify_cells(df, threshold=3):
    """
    Classifies neurons based on gene count thresholds.
    Ref: Methodology for determining EASI-FISH cell-type identity.
    """
    logger.info(f"Classifying cells with threshold: {threshold}")
    
    # Ensure columns exist
    if 'eomesa' not in df.columns or 'pvalb7' not in df.columns:
        raise ValueError("Missing 'eomesa' or 'pvalb7' columns in count matrix.")
    
    df['eomesa_pos'] = df['eomesa'] > threshold
    df['pvalb7_pos'] = df['pvalb7'] > threshold
    df['co_expressed'] = df['eomesa_pos'] & df['pvalb7_pos']
    
    return df

def generate_spatial_mapping(df, atlas):
    """Integrates binary classification with spatial atlas metadata."""
    # Assuming atlas dataframe contains 'cell_id', 'x', 'y', 'z', and 'region_name'
    merged = df.merge(atlas, left_index=True, right_on='cell_id')
    return merged

def save_outputs(data, out_dir):
    """Saves analytical outputs to disk."""
    out_path = Path(out_dir)
    out_path.mkdir(parents=True, exist_ok=True)
    
    data.to_parquet(out_path / "classified_neurons.parquet")
    
    # Calculate summary counts for validation
    summary = {
        "eomesa_count": int(data['eomesa_pos'].sum()),
        "pvalb7_count": int(data['pvalb7_pos'].sum()),
        "co_expr_count": int(data['co_expressed'].sum())
    }
    
    with open(out_path / "summary.json", 'w') as f:
        json.dump(summary, f, indent=4)
        
    logger.info(f"Outputs saved to {out_dir}")

def main():
    parser = argparse.ArgumentParser(description="Map eomesa/pvalb7 spatial distribution.")
    parser.add_argument("--counts", required=True, help="Path to aggregated count.csv")
    parser.add_argument("--atlas", required=True, help="Path to MapZebrain metadata CSV")
    parser.add_argument("--outdir", required=True, help="Output directory")
    parser.add_argument("--threshold", type=int, default=3, help="Spot threshold (default: 3)")
    
    args = parser.parse_args()
    
    try:
        # Step 1: Load
        logger.info("Loading input files...")
        counts, atlas = load_data(args.counts, args.atlas)
        
        # Step 2: Thresholding/Classification
        classified = classify_cells(counts, args.threshold)
        
        # Step 3: Spatial Mapping
        spatial_data = generate_spatial_mapping(classified, atlas)
        
        # Step 4: Export
        save_outputs(spatial_data, args.outdir)
        
        logger.info("Analysis complete. Visualization-ready data generated.")
        
    except Exception as e:
        logger.error(f"Analysis failed: {str(e)}")
        exit(1)

if __name__ == '__main__':
    main()